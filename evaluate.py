def _find_column(df: pd.DataFrame, requested: str, candidates: list[str]):
    if requested != "auto":
        if requested not in df.columns:
            raise KeyError(f"Column {requested!r} not found. Available: {list(df.columns)}")
        return requested
    for c in candidates:
        if c in df.columns:
            return c
    return None


def canonical_morphology(value, solid_label=None, subsolid_label=None):
    if pd.isna(value):
        return None
    original = str(value).strip()
    if solid_label is not None and original.casefold() == str(solid_label).strip().casefold():
        return "Solid"
    if subsolid_label is not None and original.casefold() == str(subsolid_label).strip().casefold():
        return "Sub-solid"
    k = original.casefold().replace("_", "-").replace(" ", "-")
    if k in {"solid", "solid-nodule", "solid-nodules"}:
        return "Solid"
    if k in {"sub-solid", "subsolid", "part-solid", "partsolid", "partial-solid",
             "pure-ggo", "ggo", "pggn", "psn", "ground-glass", "ground-glass-opacity",
             "pure-ground-glass", "nonsolid", "non-solid", "groundglass"}:
        return "Sub-solid"
    # Never guess whether numeric 0/1 means solid or sub-solid.
    return None


def surface_voxels(mask):
    """One-voxel inner boundary of a binary 3D object (6-neighbor erosion)."""
    eroded = ndi.binary_erosion(mask, structure=ndi.generate_binary_structure(3, 1),
                                border_value=0)
    return mask & (~eroded)


def binary_metrics(pred: np.ndarray, gt: np.ndarray, spacing_mm=(1., 1., 1.),
                   surface_tolerance_mm=1.0):
    pred, gt = np.asarray(pred).astype(bool), np.asarray(gt).astype(bool)
    if pred.ndim != 3 or gt.shape != pred.shape:
        raise ValueError(f"Prediction/GT must be same-sized 3D masks, got {pred.shape} / {gt.shape}")
    tp = int(np.count_nonzero(pred & gt))
    fp = int(np.count_nonzero(pred & ~gt))
    fn = int(np.count_nonzero(~pred & gt))
    n_pred = tp + fp
    n_gt = tp + fn
    row = {"gt_voxels": n_gt, "pred_voxels": n_pred, "TP_v": tp, "FP_v": fp, "FN_v": fn}
    if n_gt == 0:
        row.update({metric: float("nan") for metric in METRICS})
        row["status"] = "empty_ground_truth_excluded"
        return row
    # Undefined precision with empty prediction is defined as zero explicitly.
    # Empty GT is excluded, matching the supplied train.py validation loop.
    row.update({
        "Dice (%)": 100. * (2. * tp / (2. * tp + fp + fn)),
        "IoU (%)": 100. * (tp / (tp + fp + fn)),
        "Pixel-Sens (%)": 100. * (tp / (tp + fn)),
        "Prec (%)": 100. * (tp / (tp + fp)) if n_pred > 0 else 0.,
    })
    if n_pred == 0:
        row.update({"HD95 (mm)": float("nan"), "ASD (mm)": float("nan"),
                    "Surf-Dice (%)": 0., "status": "empty_prediction_undefined_distance"})
        return row

    surf_pred = surface_voxels(pred)
    surf_gt = surface_voxels(gt)
    # At each foreground surface voxel, query distance to the opposing surface.
    dist_to_gt = ndi.distance_transform_edt(~surf_gt, sampling=spacing_mm)
    dist_to_pred = ndi.distance_transform_edt(~surf_pred, sampling=spacing_mm)
    directed_p_to_g = dist_to_gt[surf_pred]
    directed_g_to_p = dist_to_pred[surf_gt]
    hd95 = max(float(np.percentile(directed_p_to_g, 95)),
               float(np.percentile(directed_g_to_p, 95)))
    asd = 0.5 * (float(np.mean(directed_p_to_g)) + float(np.mean(directed_g_to_p)))
    matched_surfaces = (int(np.count_nonzero(directed_p_to_g <= surface_tolerance_mm))
                        + int(np.count_nonzero(directed_g_to_p <= surface_tolerance_mm)))
    denom_surfaces = directed_p_to_g.size + directed_g_to_p.size
    row.update({"HD95 (mm)": hd95, "ASD (mm)": asd,
                "Surf-Dice (%)": 100. * matched_surfaces / denom_surfaces,
                "status": "ok"})
    return row


def volume_equivalent_diameter(gt_full: np.ndarray, spacing_mm):
    """Volume-equivalent spherical diameter in physical mm from the full reference ROI."""
    count = int(np.count_nonzero(gt_full))
    if count == 0:
        return float("nan")
    volume_mm3 = count * float(np.prod(spacing_mm))
    return float((6.0 * volume_mm3 / math.pi) ** (1.0 / 3.0))


def size_category(diameter_mm: float, size_rule: str, threshold_mm: float):
    if not np.isfinite(diameter_mm):
        return None
    formatted = f"{threshold_mm:g}mm"
    if size_rule == "le":
        return f"<={formatted}" if diameter_mm <= threshold_mm else f">{formatted}"
    return f"<{formatted}" if diameter_mm < threshold_mm else f">={formatted}"


def group_summary(df: pd.DataFrame, group_name: str, group_value: str):
    row = {"group_by": group_name, "group": group_value,
           "n_nodules": len(df),
           "n_patients": (df["patient_id"].nunique() if "patient_id" in df and df["patient_id"].notna().all() else None),
           "n_empty_predictions": int((df["status"] == "empty_prediction_undefined_distance").sum())}
    for metric in METRICS:
        vals = pd.to_numeric(df[metric], errors="coerce")
        row[metric] = float(vals.mean()) if vals.notna().any() else None
        row[f"n_{metric}"] = int(vals.notna().sum())
    return row


def patient_clustered_ci(df: pd.DataFrame, metric: str, n_boot: int, seed: int,
                         unit: str):
    """Percentile bootstrap of the nodule-weighted cohort mean.

    Each resampled patient contributes ALL their nodules; per-nodule averaging
    remains the estimand rather than averaging patients equally.
    """
    valid = df[[metric, "patient_id"]].copy()
    valid[metric] = pd.to_numeric(valid[metric], errors="coerce")
    valid = valid.dropna(subset=[metric])
    if valid.empty:
        return (None, None, 0)
    values = valid[metric].to_numpy(dtype=np.float64)
    rng = np.random.default_rng(seed)
    if unit == "nodule":
        group_sums = values
        group_counts = np.ones(len(values), dtype=np.float64)
    else:
        if valid["patient_id"].isna().any():
            raise ValueError("Patient-clustered bootstrap requires real, non-missing patient IDs")
        grouped = valid.groupby("patient_id", sort=True)[metric]
        group_sums = grouped.sum().to_numpy(dtype=np.float64)
        group_counts = grouped.size().to_numpy(dtype=np.float64)
    n_groups = len(group_sums)
    if n_groups < 2:
        return (None, None, n_groups)
    # Batch resampling for moderate cohort sizes; no huge bootstrap array.
    results = np.empty(n_boot, dtype=np.float64)
    for k in range(0, n_boot, 256):
        n = min(256, n_boot - k)
        indices = rng.integers(0, n_groups, size=(n, n_groups))
        results[k:k+n] = group_sums[indices].sum(axis=1) / group_counts[indices].sum(axis=1)
    lo, hi = np.percentile(results, [2.5, 97.5])
    return (float(lo), float(hi), n_groups)


def patient_paired_tests(current: pd.DataFrame, reference_path: Path):
    """Per-patient paired t tests; requires true patient IDs in both files."""
    if "patient_id" not in current or current["patient_id"].isna().any():
        raise ValueError("Paired patient comparisons require patient IDs in current CSV")
    reference = pd.read_csv(reference_path, dtype={"patient_id": str, "FileName": str})
    if "patient_id" not in reference or reference["patient_id"].isna().any():
        raise ValueError("Reference per-nodule CSV must include non-missing patient_id")
    if current["FileName"].duplicated().any() or reference["FileName"].duplicated().any():
        raise ValueError("Nonunique FileName prevents exact paired comparison")
    if "crop_mode" not in reference or set(reference["crop_mode"].dropna()) != set(current["crop_mode"].dropna()):
        raise ValueError("配对比较要求两个模型使用完全相同的crop_mode")
    for key in ("crop_start_z", "crop_start_y", "crop_start_x"):
        if key not in reference:
            raise ValueError(f"配对参考文件缺少{key}，无法核对裁剪区域")
    paired_geometry = current[["FileName", "crop_mode", "crop_start_z", "crop_start_y", "crop_start_x"]].merge(
        reference[["FileName", "crop_mode", "crop_start_z", "crop_start_y", "crop_start_x"]],
        on="FileName", how="inner", suffixes=("_a", "_b"), validate="one_to_one")
    for key in ("crop_mode", "crop_start_z", "crop_start_y", "crop_start_x"):
        if (paired_geometry[f"{key}_a"].astype(str) != paired_geometry[f"{key}_b"].astype(str)).any():
            raise ValueError(f"两模型配对结节使用不同的{key}，不能直接比较")
    all_rows = []
    for metric in METRICS:
        if metric not in reference:
            continue
        merged = current[["FileName", "patient_id", metric]].merge(
            reference[["FileName", "patient_id", metric]], on="FileName", how="inner",
            suffixes=("_dssw", "_ref"), validate="one_to_one")
        if merged.empty:
            continue
        if (merged["patient_id_dssw"].astype(str) !=
                merged["patient_id_ref"].astype(str)).any():
            raise ValueError("Patient ID mismatch between models for matched nodules")
        merged = merged.dropna(subset=[metric + "_dssw", metric + "_ref"])
        grouped = merged.groupby("patient_id_dssw")[[metric+"_dssw", metric+"_ref"]].mean()
        n = len(grouped)
        p = (float(ttest_rel(grouped[metric+"_dssw"], grouped[metric+"_ref"]).pvalue)
             if n >= 2 else float("nan"))
        mean_diff = float((grouped[metric+"_dssw"] - grouped[metric+"_ref"]).mean()) if n else float("nan")
        all_rows.append({"metric": metric, "n_matched_nodules": len(merged),
                         "n_matched_patients": n, "patient_mean_difference": mean_diff,
                         "p_value_two_sided_paired_t": p,
                         "p_value_adjusted": False})
    return pd.DataFrame(all_rows)


def combine_three_runs(csv_paths, output_dir, n_boot=2000, seed=42,
                       reference_paths=None):
    """Manuscript-protocol summary from *actual* independently generated per-nodule CSVs.

    Per-run mean -> across-three-runs mean +/- SD; per-nodule three-run mean ->
    patient-clustered percentile bootstrap. Does NOT use mean+/-SD to invent CI.
    """
    if len(csv_paths) != 3 or n_boot < 1:
        raise ValueError('Exactly 3 run CSVs and a positive n_boot are required')

    def load_runs(paths, model_name):
        runs = []
        for file in paths:
            if not Path(file).is_file():
                raise FileNotFoundError(file)
            df = pd.read_csv(file, dtype={'FileName': str, 'patient_id': str})
            necessary = ['FileName', 'patient_id', *METRICS]
            missing = [name for name in necessary if name not in df.columns]
            if missing:
                raise KeyError(f'{file} missing {missing}')
            if df['FileName'].isna().any() or df['FileName'].duplicated().any():
                raise ValueError(f'{file}: invalid FileName IDs')
            if df['patient_id'].isna().any() or df['patient_id'].str.strip().eq('').any():
                raise ValueError(f'{file}: real patient_id is required for clustered CI')
            if df['patient_id'].nunique() < 2:
                raise ValueError(f'{file}: at least 2 independent patients needed')
            df = df.sort_values('FileName').reset_index(drop=True)
            for col in METRICS:
                df[col] = pd.to_numeric(df[col], errors='coerce')
            runs.append(df)
        canonical = runs[0]
        for run in runs[1:]:
            if not run['FileName'].equals(canonical['FileName']):
                raise ValueError(f'{model_name}: run files refer to different nodules')
            if not run['patient_id'].equals(canonical['patient_id']):
                raise ValueError(f'{model_name}: patient IDs vary between runs')
            for col in ('crop_mode', 'crop_start_z', 'crop_start_y', 'crop_start_x'):
                if col in canonical and col in run and not run[col].astype(str).equals(canonical[col].astype(str)):
                    raise ValueError(f'{model_name}: different crop geometry across runs ({col})')
        return runs

    ours = load_runs(csv_paths, 'DSSW-Net')
    ref = load_runs(reference_paths, 'MedNeXt') if reference_paths else None
    if ref is not None:
        for run in ref:
            if not run['FileName'].equals(ours[0]['FileName']):
                raise ValueError('Comparative models have different test nodules')
            if not run['patient_id'].equals(ours[0]['patient_id']):
                raise ValueError('Comparative models have different patient IDs')
            # Comparison must not mix a center-cropped 64^3 patch with sliding 96^3 masks.
            for field in ('crop_mode', 'crop_start_z', 'crop_start_y', 'crop_start_x'):
                if field not in run or field not in ours[0]:
                    raise ValueError(f'Missing geometry column {field} for cross-model comparison')
                if not run[field].astype(str).equals(ours[0][field].astype(str)):
                    raise ValueError(f'Comparative models used different crop geometry ({field})')

    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    averaged = ours[0][['FileName', 'patient_id']].copy()
    summary_rows, ci_rows, test_rows = [], [], []
    for idx, metric in enumerate(METRICS):
        individual_means = np.array([d[metric].mean() for d in ours], dtype=float)
        if not np.isfinite(individual_means).all():
            raise ValueError(f'No valid run-level mean for {metric}')
        summary_rows.append({'model': 'DSSW-Net', 'metric': metric, 'n_runs': 3,
                             'mean': individual_means.mean(),
                             'sd_across_runs': individual_means.std(ddof=1),
                             'run1': individual_means[0], 'run2': individual_means[1],
                             'run3': individual_means[2]})
        arr = np.stack([d[metric].to_numpy(dtype=float) for d in ours], axis=0)
        # Preserve NaN if no run has valid surface metric. Report valid n precisely.
        valid_any = np.isfinite(arr).any(axis=0)
        mean_arr = np.full(arr.shape[1], np.nan, dtype=float)
        mean_arr[valid_any] = np.nanmean(arr[:, valid_any], axis=0)
        averaged[metric] = mean_arr
        lo, hi, clusters = patient_clustered_ci(averaged, metric, n_boot, seed + idx, 'patient')
        ci_rows.append({'model': 'DSSW-Net', 'metric': metric,
                        'mean_nodule_average_of_three_runs': averaged[metric].mean(),
                        'CI95_lower': lo, 'CI95_upper': hi,
                        'n_patients': clusters, 'n_valid_nodules': int(averaged[metric].notna().sum()),
                        'bootstrap_iterations': n_boot})
        if ref is not None:
            ref_means = np.array([d[metric].mean() for d in ref], dtype=float)
            if not np.isfinite(ref_means).all():
                raise ValueError(f'Reference model has empty {metric} run mean')
            summary_rows.append({'model': 'MedNeXt', 'metric': metric, 'n_runs': 3,
                                 'mean': ref_means.mean(),
                                 'sd_across_runs': ref_means.std(ddof=1),
                                 'run1': ref_means[0], 'run2': ref_means[1],
                                 'run3': ref_means[2]})
            ref_arr = np.stack([d[metric].to_numpy(dtype=float) for d in ref], axis=0)
            ref_valid = np.isfinite(ref_arr).any(axis=0)
            ref_avg = averaged[['FileName', 'patient_id']].copy()
            ref_metric = np.full(ref_arr.shape[1], np.nan, dtype=float)
            ref_metric[ref_valid] = np.nanmean(ref_arr[:, ref_valid], axis=0)
            ref_avg[metric] = ref_metric
            rlo, rhi, rn = patient_clustered_ci(ref_avg, metric, n_boot, seed+100+idx, 'patient')
            ci_rows.append({'model': 'MedNeXt', 'metric': metric,
                            'mean_nodule_average_of_three_runs': ref_avg[metric].mean(),
                            'CI95_lower': rlo, 'CI95_upper': rhi, 'n_patients': rn,
                            'n_valid_nodules': int(ref_avg[metric].notna().sum()),
                            'bootstrap_iterations': n_boot})
            test = ttest_ind(individual_means, ref_means, equal_var=False, alternative='two-sided')
            test_rows.append({'metric': metric, 'test': 'unadjusted_two_sided_Welch_run_level',
                              'n_runs_each': 3, 'p_value': float(test.pvalue),
                              'mean_difference': float(individual_means.mean()-ref_means.mean())})
    averaged.to_csv(output_dir/'per_nodule_three_run_averages.csv', index=False, encoding='utf-8-sig')
    pd.DataFrame(summary_rows).to_csv(output_dir/'three_run_mean_sd.csv', index=False, encoding='utf-8-sig')
    pd.DataFrame(ci_rows).to_csv(output_dir/'three_run_patient_clustered_ci.csv', index=False, encoding='utf-8-sig')
    if test_rows:
        pd.DataFrame(test_rows).to_csv(output_dir/'three_run_welch.csv', index=False, encoding='utf-8-sig')
    print('[three-run analysis] results saved:', output_dir)


def main():
    args = parse_args()
    if args.reference_run_csvs and not args.run_csvs:
        raise ValueError('--reference-run-csvs requires --run-csvs')
    if args.run_csvs is not None:
        combine_three_runs(args.run_csvs, args.output_dir,
                           n_boot=args.bootstrap or AUTO_PATIENT_BOOTSTRAP_ITERATIONS,
                           seed=args.seed, reference_paths=args.reference_run_csvs)
        return
    if any(x <= 0 for x in args.spacing_mm):
        raise ValueError("All spacings must be > 0")
    if args.surface_tolerance_mm < 0:
        raise ValueError("--surface-tolerance-mm must be >= 0")
    if args.bootstrap < 0:
        raise ValueError("--bootstrap must be >= 0")
    if not args.manifest.is_file():
        raise FileNotFoundError(
            f"没有找到推理清单：{args.manifest}\n"
            "请先在 PyCharm 运行 inference.py，生成 inference_manifest.csv。"
        )
    if not args.mask_dir.is_dir():
        raise FileNotFoundError(
            f"没有找到真实结节掩码目录：{args.mask_dir}\n"
            "请检查 DEFAULT_MASK_DIR 是否与你原来的 train.py 一致。"
        )
    data = pd.read_csv(args.manifest, dtype=str)
    print(f"读取推理清单：{args.manifest}")
    subsets = sorted(data["subset"].dropna().unique().tolist()) if "subset" in data else []
    print(f"数据划分：{subsets}")
    if any(x != "test" for x in subsets):
        print("WARNING: 当前含验证集或其他分组，不可把此结果当成独立test指标！")
    for column in ["FileName", "pred_path", "crop_start_z", "crop_start_y", "crop_start_x"]:
        if column not in data:
            raise KeyError(f"Missing {column!r} in manifest; use inference.py to generate it")
    if data.empty:
        raise ValueError("Empty inference manifest")
    if data["FileName"].isna().any() or data["FileName"].duplicated().any():
        raise ValueError("Null or duplicate FileName in manifest")
    if "crop_mode" not in data:
        raise KeyError("推理清单缺少crop_mode；必须知道预测是64^3 Patch还是完整96^3 ROI")
    modes = set(data["crop_mode"].dropna())
    accepted_modes = {"center64", "sliding64"}
    if len(modes) != 1 or not modes.issubset(accepted_modes):
        raise ValueError(f"每份评价仅接受一种推理协议，得到: {modes}；避免混合64/96结果")
    inference_mode = next(iter(modes))
    patient_col = _find_column(data, args.patient_column, PATIENT_COLUMNS)
    morphology_col = _find_column(data, args.morphology_column, MORPHOLOGY_COLUMNS)
    output_dir = args.output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    print(f"Evaluating {len(data)} nodules using mode={inference_mode}, spacing (z,y,x)={tuple(args.spacing_mm)} mm")
    print("NOTE: spacing is supplied through CLI; NumPy ROI files contain no affine/physical metadata.")
    if patient_col is None:
        print("WARNING: no patient ID column found; patient-clustered CI and paired patient tests are unavailable.")
    if morphology_col is None:
        print("WARNING: no morphology column found; Solid/Sub-solid subgroup table will not be produced.")
    # 用户直接在 PyCharm 点击运行：如果有真实患者编号，则默认自动生成95% CI。
    # 若显式传入 --bootstrap，则遵循用户指定次数，不悄悄修改。
    explicitly_set_bootstrap = any(
        x == "--bootstrap" or x.startswith("--bootstrap=") for x in sys.argv[1:]
    )
    if not explicitly_set_bootstrap and args.bootstrap == 0:
        has_real_ids = (patient_col is not None
                        and data[patient_col].notna().all()
                        and data[patient_col].astype(str).str.strip().ne("").all()
                        and data[patient_col].nunique() >= 2)
        if has_real_ids:
            args.bootstrap = AUTO_PATIENT_BOOTSTRAP_ITERATIONS
            print(f"自动识别患者列 {patient_col!r}，进行 {args.bootstrap} 次患者聚类 Bootstrap。")
        else:
            print("[注意] 没有完整可靠的患者ID，自动跳过患者聚类CI。不会根据文件名捏造患者ID。")
    if args.bootstrap > 0 and args.bootstrap_unit == "patient" and patient_col is None:
        raise ValueError("Cannot claim patient-clustered CI without patient IDs: "
                         "add --patient-column COL or choose --bootstrap-unit nodule explicitly")
    if args.bootstrap > 0 and args.bootstrap_unit == "nodule":
        print("WARNING: nodule bootstrap assumes nodules independent; NOT patient-clustered.")

    records = []
    unknown_morph = set()
    for idx, (_, src) in enumerate(data.iterrows(), 1):
        filename = str(src["FileName"])
        if not filename or Path(filename).name != filename:
            raise ValueError(f"无效的FileName: {filename}")
        path_pred = Path(str(src["pred_path"]))
        if not path_pred.is_file():
            fallback = args.manifest.parent / "predictions" / filename
            if fallback.is_file():
                path_pred = fallback
            else:
                raise FileNotFoundError(f"Prediction not found: {path_pred}; fallback={fallback}")
        path_gt = args.mask_dir / filename
        if not path_gt.is_file():
            raise FileNotFoundError(path_gt)
        pred = np.load(path_pred, allow_pickle=False)
        gt_full = np.load(path_gt, allow_pickle=False)
        if gt_full.ndim != 3 or pred.ndim != 3:
            raise ValueError(f"Expected 3D masks for {filename}, got {pred.shape}, {gt_full.shape}")
        if gt_full.shape != (96, 96, 96):
            raise ValueError(f"{filename}: 当前preprocess.py输出应为96^3，GT={gt_full.shape}")
        starts = tuple(int(src.get(f"crop_start_{axis}", 0)) for axis in "zyx")
        mode = str(src["crop_mode"])
        if mode == "center64":
            size = int(src.get("crop_size", 64))
            if pred.shape != (size, size, size):
                raise ValueError(f"{filename}: Patch预测应是{size}^3，实际{pred.shape}")
            if any(start < 0 or start + size > dim
                   for start, dim in zip(starts, gt_full.shape)):
                raise ValueError(f"{filename}: GT裁剪坐标越界: {starts}, size={size}")
            gt_crop = gt_full[tuple(slice(s, s + size) for s in starts)]
        elif mode == "sliding64":
            if pred.shape != gt_full.shape:
                raise ValueError(f"{filename}: 完整ROI预测与GT尺寸不同: {pred.shape} vs {gt_full.shape}")
            if starts != (0, 0, 0):
                raise ValueError(f"{filename}: 完整ROI模式不应具有非零crop_start")
            gt_crop = gt_full
        else:
            raise ValueError(f"不支持的推理模式: {mode}")
        # 逐结节指标只能评价与推理patch相同的空间；不能把64预测直接与96 GT比较。
        # 对中心64 patch，如果目标结节没有落入裁剪区域，直接报错以防静默丢样本。
        if not np.any(gt_crop > args.gt_threshold):
            raise ValueError(f"{filename}: 此{mode}预测区域没有真实结节；不能静默排除该病例")
        pred_bool = pred > args.pred_threshold
        gt_bool = gt_crop > args.gt_threshold
        results = binary_metrics(pred_bool, gt_bool, args.spacing_mm, args.surface_tolerance_mm)
        diam = volume_equivalent_diameter(gt_full > args.gt_threshold, args.spacing_mm)
        morphology = None
        if morphology_col is not None:
            raw_value = src[morphology_col]
            morphology = canonical_morphology(raw_value, args.solid_label, args.subsolid_label)
            if morphology is None and not pd.isna(raw_value):
                unknown_morph.add(str(raw_value))
        patient_id = src[patient_col] if patient_col else None
        rec = {"FileName": filename, "patient_id": patient_id,
               "subset": src.get("subset", "unknown"),
               "crop_mode": src.get("crop_mode", "unknown"),
               "crop_start_z": starts[0], "crop_start_y": starts[1], "crop_start_x": starts[2],
               "diameter_mm": diam, "size_group": size_category(diam, args.size_rule, args.size_threshold_mm),
               "morphology": morphology, **results}
        records.append(rec)
        if idx == 1 or idx % 25 == 0 or idx == len(data):
            print(f"[{idx}/{len(data)}] {filename}: Dice={rec['Dice (%)']:.3f}, status={rec['status']}")

    all_results = pd.DataFrame(records)
    per_case_path = output_dir / "per_nodule_metrics.csv"
    all_results.to_csv(per_case_path, index=False, encoding="utf-8-sig")
    if unknown_morph:
        print("WARNING: Unrecognized morphology labels:", sorted(unknown_morph),
              "-- explicitly set --solid-label and --subsolid-label if numeric")
    used = all_results[all_results["status"] != "empty_ground_truth_excluded"].copy()
    if used.empty:
        raise ValueError("No valid GT nodules available for evaluation")
    subgroup_rows = [group_summary(used, "overall", "all")]
    for label in ("size_group", "morphology"):
        for group, df in used.dropna(subset=[label]).groupby(label, sort=True):
            subgroup_rows.append(group_summary(df, label, str(group)))
    summary_df = pd.DataFrame(subgroup_rows)
    summary_df.to_csv(output_dir / "subgroup_summary.csv", index=False, encoding="utf-8-sig")
    overall = summary_df.iloc[0].to_dict()
    summary = {
        "n_manifest": len(all_results), "n_gt_valid": len(used), "inference_mode": inference_mode,
        "n_gt_empty_excluded": int((all_results["status"] == "empty_ground_truth_excluded").sum()),
        "n_empty_predictions": int((used["status"] == "empty_prediction_undefined_distance").sum()),
        "n_unique_patients": int(used["patient_id"].nunique()) if used["patient_id"].notna().all() else None,
        "spacing_mm_zyx": [float(x) for x in args.spacing_mm],
        "surface_tolerance_mm": args.surface_tolerance_mm,
        "size_threshold_mm": args.size_threshold_mm, "size_rule": args.size_rule,
        "metric_methods": {
            "aggregation": "unweighted mean of valid nodule scores",
            "Dice": "2TP/(2TP+FP+FN)", "HD95": "max of directed surface-distance 95th percentiles",
            "ASD": "mean of two directed mean surface distances",
            "Surf-Dice": "symmetric voxel-surface-count Dice at chosen mm tolerance",
            "empty_GT": "a GT-empty prediction region triggers error; do not exclude hidden failures",
            "empty_prediction": "Dice=0, HD95/ASD undefined and excluded from boundary mean; see counts",
            "ROI": f"{inference_mode}; 96^3 saved ROI, 64^3 model patch, not whole-lung detection",
        },
        "metrics": {m: {"mean": float(overall[m]) if pd.notna(overall[m]) else None,
                        "valid_n": int(overall[f"n_{m}"])} for m in METRICS},
    }

    if args.bootstrap > 0:
        ci_records = []
        for group_index, group_row in summary_df.iterrows():
            label, group = group_row["group_by"], group_row["group"]
            selected = (used if label == "overall" else used[used[label] == group])
            if args.bootstrap_unit == "patient" and selected["patient_id"].isna().any():
                raise ValueError("Missing patient ID in group: " + str(group))
            for j, m in enumerate(METRICS):
                lo, hi, nclusters = patient_clustered_ci(
                    selected, m, args.bootstrap,
                    args.seed + group_index * len(METRICS) + j, args.bootstrap_unit)
                ci_records.append({"group_by": label, "group": group, "metric": m,
                                   "mean": float(group_row[m]) if pd.notna(group_row[m]) else None,
                                   "CI95_lower": lo, "CI95_upper": hi,
                                   "n_resampled_units": nclusters,
                                   "bootstrap_unit": args.bootstrap_unit,
                                   "iterations": args.bootstrap})
        pd.DataFrame(ci_records).to_csv(output_dir / "bootstrap_ci.csv", index=False,
                                        encoding="utf-8-sig")
        summary["bootstrap"] = {"unit": args.bootstrap_unit, "iterations": args.bootstrap,
                                "method": "percentile 2.5/97.5 resampling, preserving patient clusters"}
    if args.compare_per_nodule is not None:
        if not args.compare_per_nodule.is_file():
            raise FileNotFoundError(args.compare_per_nodule)
        comparison = patient_paired_tests(used, args.compare_per_nodule)
        comparison.insert(0, "comparison_name", args.comparison_name)
        comparison.to_csv(output_dir / "paired_comparison.csv", index=False,
                          encoding="utf-8-sig")
        summary["paired_comparison"] = {"name": args.comparison_name,
                                         "method": "two-sided paired t-test on patient-averaged nodule metrics",
                                         "multiple_test_correction": "none"}
    (output_dir / "summary.json").write_text(json.dumps(summary, indent=2, ensure_ascii=False),
                                               encoding="utf-8")
    print("\n=== Overall nodule-averaged results ===")
    for m in METRICS:
        d = summary["metrics"][m]
        print(f"  {m:<20}: {d['mean']:.4f}  [n={d['valid_n']}]" if d["mean"] is not None
              else f"  {m:<20}: unavailable [n=0]")
    print(f"Saved CSV/JSON outputs to {output_dir}")
    print("[完成] 请查看 per_nodule_metrics.csv、subgroup_summary.csv、summary.json。")
    if summary["n_empty_predictions"]:
        print("WARNING: Empty predictions have undefined HD95/ASD; valid counts differ from Dice! "
              "Disclose or predefine a suitable handling rule in the paper.")


if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        print(f"EVALUATION FAILED: {e}", file=sys.stderr)
        raise
