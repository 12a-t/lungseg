"""Evaluate DSSW-Net 64^3 patch or reconstructed 96^3 ROI predictions from inference.py.

Primary outputs:
  per_nodule_metrics.csv  -- per-nodule Dice, IoU, Sensitivity, Precision,
                             HD95, ASD, Surface Dice (1-mm tolerance)
  summary.json           -- cohort means and exact valid-case counts
  subgroup_summary.csv   -- size and morphology summaries, when metadata exists
  bootstrap_ci.csv       -- automatic when real patient IDs are provided, 2000 resamples
  paired_comparison.csv  -- optional patient-level paired t-tests vs another model

This script operates on preprocessed nodule ROIs, NOT whole-lung CT.
For center64 predictions, crop GT using the *recorded prediction crop origin*.
The size-based subgroup diameter is always derived from the FULL 96^3 GT mask.
For HD95 and surface distances the .npy file contains no spatial metadata;
--spacing-mm MUST match the physical spacing of the saved ROI. Defaults to
(1,1,1) mm as stated in the paper, not automatically verified from the .npy.

HD95 = max of the two directed 95th-percentile nearest-surface distances.
ASD = average of the two directed mean nearest-surface distances.
Surf-Dice = count-based symmetric tolerance surface Dice computed at voxel
centers (not surface-area-weighted); implementation definitions must match
any claims made in a manuscript.
"""

